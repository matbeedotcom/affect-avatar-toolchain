"""Persona-vectors pipeline helpers (Chen et al. 2025, arXiv:2507.21509).

Skeleton for Phase 5 D1.0+. Encodes the pinned decisions from
docs/references/activation-steering-audio-llm/notes/spike-f-persona-vectors-pipeline.md:

- Axis-as-trait modeling (3 bipolar V/A/D directions).
- Response-token mean pooling for direction extraction.
- 0-100 LLM-judge net rubric for validation.
- Cross-model judging (judge != target) to avoid self-grading bias.

I/O helpers (load/save) are fully implemented. LLM-calling functions
(elicit_*, run_target_llm, judge_response) raise NotImplementedError;
they are filled in by the D1.0 smoke-test PR with concrete provider
adapters (Anthropic, OpenAI, local llama-cpp via subprocess).
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from enum import Enum
from pathlib import Path
from typing import Iterable, Iterator, Literal, Protocol


# ---------------------------------------------------------------------------
# Pinned constants (do not change without revisiting Spike F)
# ---------------------------------------------------------------------------

class Axis(str, Enum):
    VALENCE = "valence"
    AROUSAL = "arousal"
    DOMINANCE = "dominance"


class Pole(str, Enum):
    POSITIVE = "positive"
    NEGATIVE = "negative"


AXES: tuple[Axis, ...] = (Axis.VALENCE, Axis.AROUSAL, Axis.DOMINANCE)

# Per persona-vectors paper Appendix A.1.
N_POS_PROMPTS_PER_AXIS = 5
N_NEG_PROMPTS_PER_AXIS = 5
N_QUESTIONS_PER_AXIS = 40

# Per Appendix A.3: response-token averaging beats prompt-token / last-token.
PoolingStrategy = Literal["response_mean"]
DEFAULT_POOLING: PoolingStrategy = "response_mean"

# Per spike-f memo §"Concrete changes to plan documents": passes if
# steered@α=+1 net-score gap >= +15 and steered@α=-1 net-score gap <= -15.
JUDGE_PASS_THRESHOLD_POINTS = 15.0


# ---------------------------------------------------------------------------
# Data structures
# ---------------------------------------------------------------------------

@dataclass(frozen=True)
class TraitDescription:
    """One bipolar axis description. Loaded from data/trait_descriptions.json."""
    axis: Axis
    positive_pole: str
    negative_pole: str
    context: str


@dataclass(frozen=True)
class ContrastPair:
    """One row of contrast_pairs.jsonl.

    Generated by 02b_generate_contrast_pairs.py; consumed by
    03_extract_llm_directions.py.
    """
    axis: Axis
    pole: Pole
    system_prompt: str
    question: str

    def to_jsonl(self) -> str:
        return json.dumps(
            {
                "axis": self.axis.value,
                "pole": self.pole.value,
                "system_prompt": self.system_prompt,
                "question": self.question,
            },
            ensure_ascii=False,
        )


@dataclass(frozen=True)
class JudgeScore:
    """One LLM-judge rating. 0-100 net (positive_pole_score - negative_pole_score)."""
    axis: Axis
    response: str
    positive_pole_score: float
    negative_pole_score: float

    @property
    def net(self) -> float:
        return self.positive_pole_score - self.negative_pole_score


# ---------------------------------------------------------------------------
# Provider abstractions (filled in by D1.0)
# ---------------------------------------------------------------------------

class ElicitationLLM(Protocol):
    """LLM that drafts contrast prompts. Used once, offline, archived."""
    def complete(self, system: str, user: str) -> str: ...


class TargetLLM(Protocol):
    """The frozen LLM whose directions we are extracting.

    Conceptually wraps the existing crates/core/src/nodes/llama_cpp/
    activation extractor; called via subprocess from Python in the D1.0
    implementation. Returns hidden-state vectors at a given layer,
    pooled over response tokens only.
    """
    def generate_and_pool_response(
        self,
        system_prompt: str,
        question: str,
        layer: int,
        pooling: PoolingStrategy = DEFAULT_POOLING,
    ) -> "list[float]":  # n_embd-dim vector
        ...


class JudgeLLM(Protocol):
    """LLM scoring response trait expression on a 0-100 scale.

    MUST be a different model than TargetLLM (avoid self-grading bias).
    Per paper Appendix B: 94.7% agreement with human raters in their setup.
    """
    def score(self, axis: Axis, pole: Pole, response: str, trait_description: TraitDescription) -> float: ...


