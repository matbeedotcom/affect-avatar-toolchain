@dataclass
class SmokeTestResult:
    """Output of the D1.0 prerequisite smoke test (PROJECT_PLAN §10 R9)."""
    model_name: str
    layer: int
    per_axis: dict[Axis, dict[str, float]] = field(default_factory=dict)
    passed: bool = False
    failure_reason: str | None = None

    def axis_passed(self, axis: Axis) -> bool:
        block = self.per_axis.get(axis, {})
        return (
            block.get("gap_pos", 0.0) >= JUDGE_PASS_THRESHOLD_POINTS
            and block.get("gap_neg", 0.0) <= -JUDGE_PASS_THRESHOLD_POINTS
        )
