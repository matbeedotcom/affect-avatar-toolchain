def elicit_contrast_prompts_for_axis(
    trait: TraitDescription,
    elicitation_llm: ElicitationLLM,
    n_pos: int = N_POS_PROMPTS_PER_AXIS,
    n_neg: int = N_NEG_PROMPTS_PER_AXIS,
    n_questions: int = N_QUESTIONS_PER_AXIS,
) -> Iterator[ContrastPair]:
    """Generate n_pos*n_questions positive + n_neg*n_questions negative pairs for one axis.

    Persona-vectors pipeline (paper App. A.1 / App. D template). For each
    axis, makes 3 elicitation calls:

      1. n_pos system prompts that induce the *positive* pole.
      2. n_neg system prompts that induce the *negative* pole.
      3. n_questions evaluation questions that surface the trait.

    The cartesian product (system_prompt × question) per pole is the
    contrast set: n_pos × n_questions positive pairs + n_neg × n_questions
    negative pairs.

    Each elicitation response is parsed as a numbered line list; the
    parser tolerates `1.`, `1)`, `- `, leading whitespace, and blank lines.
    """
    pos_prompts = _elicit_lines(
        elicitation_llm,
        system=_SYSTEM_PROMPT_AUTHOR,
        user=_user_for_pole_prompts(trait, Pole.POSITIVE, n_pos),
        expected_count=n_pos,
    )
    neg_prompts = _elicit_lines(
        elicitation_llm,
        system=_SYSTEM_PROMPT_AUTHOR,
        user=_user_for_pole_prompts(trait, Pole.NEGATIVE, n_neg),
        expected_count=n_neg,
    )
    questions = _elicit_lines(
        elicitation_llm,
        system=_QUESTION_AUTHOR,
        user=_user_for_questions(trait, n_questions),
        expected_count=n_questions,
    )

    for sp in pos_prompts:
        for q in questions:
            yield ContrastPair(axis=trait.axis, pole=Pole.POSITIVE, system_prompt=sp, question=q)
    for sp in neg_prompts:
        for q in questions:
            yield ContrastPair(axis=trait.axis, pole=Pole.NEGATIVE, system_prompt=sp, question=q)


# ---------------------------------------------------------------------------
# Elicitation prompt templates (paper App. A.1 / App. D, adapted)
# ---------------------------------------------------------------------------

_SYSTEM_PROMPT_AUTHOR = (
    "You are an expert prompt engineer designing system prompts for a controlled "
    "experiment on a frozen LLM. The experiment measures how strongly a target "
    "trait is expressed when the model is steered toward one pole of a "
    "Valence/Arousal/Dominance axis. Your job is to write a varied set of system "
    "prompts that induce the requested pole behaviorally — without changing the "
    "underlying assistant's helpfulness."
)

_QUESTION_AUTHOR = (
    "You are an expert prompt engineer designing evaluation questions for a "
    "controlled experiment on a frozen LLM. Your questions should be neutral, "
    "open-ended, and conversational so that any tonal differences in the response "
    "are attributable to the model's persona rather than the question's content."
)


def _user_for_pole_prompts(trait: TraitDescription, pole: Pole, n: int) -> str:
    pole_text = trait.positive_pole if pole == Pole.POSITIVE else trait.negative_pole
    return (
        f"Axis: {trait.axis.value} ({pole.value} pole)\n"
        f"Pole description:\n{pole_text}\n\n"
        f"Context:\n{trait.context}\n\n"
        f"Write exactly {n} distinct system prompts that induce the {pole.value} "
        f"pole of {trait.axis.value}. Each prompt should:\n"
        f"  - vary in phrasing and angle (different metaphors, different tone hints),\n"
        f"  - induce the pole through tone/cadence/stance, not by changing facts,\n"
        f"  - be 1-3 sentences, written as instructions to a helpful assistant.\n\n"
        f"Output a numbered list. One prompt per line. No commentary, no headers."
    )


def _user_for_questions(trait: TraitDescription, n: int) -> str:
    return (
        f"Axis: {trait.axis.value}\n"
        f"Positive-pole description:\n{trait.positive_pole}\n\n"
        f"Negative-pole description:\n{trait.negative_pole}\n\n"
        f"Context:\n{trait.context}\n\n"
        f"Write exactly {n} short evaluation questions that, when posed to an "
        f"assistant, would let a judge tell apart responses on the {trait.axis.value} "
        f"axis. Questions should:\n"
        f"  - be neutral and open-ended (not leading toward either pole),\n"
        f"  - be conversational (a user might naturally ask them),\n"
        f"  - vary in topic so the contrast set is broad.\n\n"
        f"Output a numbered list. One question per line. No commentary, no headers."
    )


def _elicit_lines(
    elicitation_llm: "ElicitationLLM",
    *,
    system: str,
    user: str,
    expected_count: int,
) -> list[str]:
    """Call the elicitation LLM and parse its response as a list of lines.

    Tolerates `1.`, `1)`, `- `, `* `, and leading whitespace. Drops blank
    lines. Returns at most `expected_count` lines (truncates over-eager
    output).
    """
    import re

    text = elicitation_llm.complete(system, user)
    lines: list[str] = []
    for raw in text.splitlines():
        s = raw.strip()
        if not s:
            continue
        # Strip numbering / bullets: "1.", "1)", "- ", "* "
        s = re.sub(r"^\s*(?:\d+[\.\)]|[-*])\s*", "", s).strip()
        if not s:
            continue
        lines.append(s)
    if len(lines) < expected_count:
        raise ValueError(
            f"elicitation produced {len(lines)} usable lines; "
            f"expected {expected_count}. Raw text:\n{text}"
        )
    return lines[:expected_count]


def extract_axis_direction(
    contrast_pairs: Iterable[ContrastPair],
    target_llm: TargetLLM,
    layer: int,
    axis: Axis,
    pooling: PoolingStrategy = DEFAULT_POOLING,
) -> "list[float]":
    """Compute v_axis = mean(positive activations) - mean(negative activations).

    See IMPLEMENTATION_PLAN §4.5 + Spike F memo for the protocol.
    """
    import numpy as np  # local import keeps the public Protocol typing-only

    import sys as _sys

    pos_acts: list[list[float]] = []
    neg_acts: list[list[float]] = []
    n_seen = 0
    for pair in contrast_pairs:
        if pair.axis != axis:
            continue
        vec = target_llm.generate_and_pool_response(
            pair.system_prompt, pair.question, layer, pooling
        )
        if pair.pole == Pole.POSITIVE:
            pos_acts.append(vec)
        else:
            neg_acts.append(vec)
        n_seen += 1
        if n_seen % 50 == 0:
            print(
                f"    extract {axis.value} {n_seen} pairs  "
                f"(pos={len(pos_acts)}, neg={len(neg_acts)})",
                file=_sys.stderr, flush=True,
            )

    if not pos_acts or not neg_acts:
        raise ValueError(
            f"extract_axis_direction({axis.value}): "
            f"need at least one positive and one negative pair; "
            f"got n_pos={len(pos_acts)} n_neg={len(neg_acts)}"
        )

    pos_mean = np.mean(np.asarray(pos_acts, dtype=np.float32), axis=0)
    neg_mean = np.mean(np.asarray(neg_acts, dtype=np.float32), axis=0)
    return (pos_mean - neg_mean).astype(np.float32).tolist()


def judge_steered_responses(
    responses_unsteered: list[str],
    responses_steered_pos: list[str],
    responses_steered_neg: list[str],
    axis: Axis,
    trait_description: TraitDescription,
    judge_llm: JudgeLLM,
) -> dict[str, float]:
    """0-100 net rubric per IMPLEMENTATION_PLAN §4.6.

    For each response, ask the judge for a positive_pole score and a
    negative_pole score (both 0-100). Net = pos - neg. Then mean over the
    batch per condition.

    Returns dict with keys:
        net_unsteered, net_steered_pos, net_steered_neg,
        gap_pos (= net_steered_pos - net_unsteered),
        gap_neg (= net_steered_neg - net_unsteered).

    Pass criterion (caller checks): gap_pos >= JUDGE_PASS_THRESHOLD_POINTS and
                                    gap_neg <= -JUDGE_PASS_THRESHOLD_POINTS.
    """

    import sys as _sys

    def _net_mean(responses: list[str], label: str) -> float:
        if not responses:
            return 0.0
        nets: list[float] = []
        for i, r in enumerate(responses):
            if not r:
                # Empty string = degenerate generation (likely bailed at the
                # first audio token). Skip; don't penalize the axis for an
                # MLX modality glitch.
                continue
            pos = judge_llm.score(axis, Pole.POSITIVE, r, trait_description)
            neg = judge_llm.score(axis, Pole.NEGATIVE, r, trait_description)
            nets.append(pos - neg)
            if (i + 1) % 10 == 0:
                print(
                    f"    judge {axis.value} {label} {i + 1}/{len(responses)}",
                    file=_sys.stderr, flush=True,
                )
        if not nets:
            return 0.0
        return float(sum(nets) / len(nets))

    net_u = _net_mean(responses_unsteered, "unsteered")
    net_p = _net_mean(responses_steered_pos, "+alpha")
    net_n = _net_mean(responses_steered_neg, "-alpha")

    return {
        "net_unsteered": net_u,
        "net_steered_pos": net_p,
        "net_steered_neg": net_n,
        "gap_pos": net_p - net_u,
        "gap_neg": net_n - net_u,
    }


