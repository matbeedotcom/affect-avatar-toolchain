def load_trait_descriptions(path: Path) -> dict[Axis, TraitDescription]:
    """Load trait_descriptions.json and validate the axis-as-trait schema."""
    with path.open("r", encoding="utf-8") as f:
        raw = json.load(f)

    out: dict[Axis, TraitDescription] = {}
    for axis in AXES:
        block = raw.get(axis.value)
        if block is None:
            raise ValueError(f"trait_descriptions.json missing required axis: {axis.value}")
        for required in ("positive_pole", "negative_pole", "context"):
            if required not in block or not isinstance(block[required], str) or not block[required].strip():
                raise ValueError(f"trait_descriptions.json axis '{axis.value}' missing/empty field: {required}")
        out[axis] = TraitDescription(
            axis=axis,
            positive_pole=block["positive_pole"],
            negative_pole=block["negative_pole"],
            context=block["context"],
        )
    return out


def load_contrast_pairs(path: Path) -> Iterator[ContrastPair]:
    """Stream contrast_pairs.jsonl one row at a time (~600 rows; fits in memory but stream by default)."""
    with path.open("r", encoding="utf-8") as f:
        for line_no, line in enumerate(f, start=1):
            line = line.strip()
            if not line:
                continue
            try:
                row = json.loads(line)
                yield ContrastPair(
                    axis=Axis(row["axis"]),
                    pole=Pole(row["pole"]),
                    system_prompt=row["system_prompt"],
                    question=row["question"],
                )
            except (KeyError, ValueError, TypeError) as exc:
                raise ValueError(f"contrast_pairs.jsonl line {line_no}: {exc}") from exc


def dump_contrast_pairs(pairs: Iterable[ContrastPair], path: Path) -> int:
    """Write contrast pairs to JSONL; returns row count."""
    n = 0
    with path.open("w", encoding="utf-8") as f:
        for pair in pairs:
            f.write(pair.to_jsonl())
            f.write("\n")
            n += 1
    return n


